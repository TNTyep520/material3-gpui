pub const ICON_COUNT: usize = ALL_ICONS.len();

pub mod materialsymbolsrounded {
    pub use super::IconName::*;
}

impl IconName {
    pub const fn ligature(&self) -> &'static str {
        self.name()
    }

    pub fn path(self) -> SharedString {
        format!("md3-icons/materialsymbolsrounded/{}.svg", self.name()).into()
    }
}

#[derive(IntoElement)]
pub struct Icon {
    name: IconName,
    size: Pixels,
    color: Option<Hsla>,
}

impl Icon {
    pub fn new(name: IconName) -> Self {
        Self {
            name,
            size: px(24.),
            color: None,
        }
    }

    pub fn ligature(name: &'static str) -> Self {
        Self::new(IconName::Custom(name))
    }

    pub fn size(mut self, size: Pixels) -> Self {
        self.size = size;
        self
    }

    pub fn color(mut self, color: Hsla) -> Self {
        self.color = Some(color);
        self
    }
}

impl RenderOnce for Icon {
    fn render(self, window: &mut Window, _cx: &mut App) -> impl IntoElement {
        svg()
            .path(self.name.path())
            .size(self.size)
            .flex_none()
            .text_color(self.color.unwrap_or_else(|| window.text_style().color))
    }
}

#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::{ALL_ICONS, ICON_COUNT, IconName, materialsymbolsrounded::Home};

    #[test]
    fn every_name_round_trips_without_collisions() {
        let mut names = HashSet::new();
        let mut paths = HashSet::new();
        for &icon in ALL_ICONS {
            assert!(names.insert(icon.name()));
            assert!(paths.insert(icon.path()));
            assert_eq!(IconName::from_name(icon.name()), Some(icon));
        }
        assert_eq!(names.len(), ICON_COUNT);
        assert!(names.len() > 4_000);
        assert_eq!(IconName::from_name("not_an_icon"), None);
    }

    #[test]
    fn existing_names_and_direct_imports_share_svg_paths() {
        assert_eq!(Home, IconName::Home);
        assert_eq!(IconName::Custom("home").path(), Home.path());
        assert_eq!(IconName::DirectionsWalk.name(), "directions_walk");
        assert_eq!(IconName::MoreVert.ligature(), "more_vert");
        assert_eq!(IconName::Remove.name(), "remove");
    }
}
